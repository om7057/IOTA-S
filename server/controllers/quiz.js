/**
 * Helper function to compare user answer with correct answer
 */
function compareAnswers(userAnswer, correctAnswer) {
  if (!userAnswer || !correctAnswer) return false;

  // For multiple choice / true false
  if (typeof correctAnswer === 'string' || typeof correctAnswer === 'boolean') {
    return userAnswer === correctAnswer;
  }

  // For arrays (multiple answers)
  if (Array.isArray(correctAnswer)) {
    if (!Array.isArray(userAnswer)) return false;
    if (userAnswer.length !== correctAnswer.length) return false;
    return userAnswer.sort().every((a, i) => a === correctAnswer.sort()[i]);
  }

  // For objects (matching, complex answers)
  if (typeof correctAnswer === 'object') {
    return JSON.stringify(userAnswer) === JSON.stringify(correctAnswer);
  }

  return false;
}

function isUuid(value) {
  return typeof value === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value);
}

async function resolveQuizUserId(authUser) {
  const authId = authUser?.id;
  const authEmail = authUser?.email;

  if (!authId && !authEmail) {
    return null;
  }

  if (authId && isUuid(authId)) {
    const byId = await User.findByPk(authId, { paranoid: false });
    if (byId) {
      return byId.id;
    }
  }

  if (authEmail) {
    const byEmail = await User.findOne({
      where: { email: String(authEmail).toLowerCase() },
      paranoid: false,
    });

    if (byEmail) {
      return byEmail.id;
    }

    const created = await User.create({
      ...(authId && isUuid(authId) ? { id: authId } : {}),
      email: String(authEmail).toLowerCase(),
      firstName: 'Learner',
      oauthProvider: 'local',
    });

    return created.id;
  }

  return null;
}

function getPeriodStart(period) {
  if (period === 'weekly') {
    return new Date(Date.now() - 7 * 24 * 60 * 60 * 1000);
  }

  if (period === 'monthly') {
    return new Date(Date.now() - 30 * 24 * 60 * 60 * 1000);
  }

  return new Date('2000-01-01');
}

async function syncLeaderboardForUser(userId) {
  const periods = ['all-time', 'monthly', 'weekly'];

  for (const period of periods) {
    const startDate = getPeriodStart(period);

    const [quizzes, stories] = await Promise.all([
      QuizProgress.findAll({
        where: {
          userId,
          completedAt: { [Op.gte]: startDate },
        },
      }),
      UserStoryProgress.findAll({
        where: {
          userId,
          status: 'completed',
          completedAt: { [Op.gte]: startDate },
        },
      }),
    ]);

    const totalQuizPoints = quizzes.reduce((sum, item) => sum + (item.pointsEarned || 0), 0);
    const totalStoryPoints = stories.reduce((sum, item) => sum + (item.pointsEarned || 0), 0);
    const totalPoints = totalQuizPoints + totalStoryPoints;

    const quizzesCompleted = new Set(quizzes.map((item) => item.quizId)).size;
    const storiesCompleted = stories.length;

    const [entry] = await Leaderboard.findOrCreate({
      where: { userId, period },
      defaults: {
        userId,
        period,
        rank: 0,
        totalPoints,
        quizzesCompleted,
        storiesCompleted,
        journalCount: 0,
        moodLogsCount: 0,
        streak: 0,
        lastActivityAt: new Date(),
        periodStartAt: startDate,
      },
    });

    if (entry) {
      await entry.update({
        totalPoints,
        quizzesCompleted,
        storiesCompleted,
        moodLogsCount: 0,
        lastActivityAt: new Date(),
        periodStartAt: startDate,
      });
    }

    const ordered = await Leaderboard.findAll({
      where: { period },
      order: [
        ['totalPoints', 'DESC'],
        ['lastActivityAt', 'ASC'],
      ],
    });

    await Promise.all(
      ordered.map((row, index) => row.update({ rank: index + 1 }))
    );
  }
}

