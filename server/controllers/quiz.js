/**
 * Submit quiz attempt and calculate score
 */
export const submitQuizAttempt = async (req, res) => {
  try {
    const { quizId } = req.params;
    const { answers = {}, timeSpent, emotionReport } = req.body || {};
    const userId = await resolveQuizUserId(req.user);

    if (!userId) {
      return res.status(401).json({
        success: false,
        error: 'Unauthorized user context',
      });
    }

    const quiz = await Quiz.findByPk(quizId, {
      include: [
        {
          model: QuizQuestion,
          as: 'questions',
          attributes: ['id', 'correctAnswer', 'points', 'sequence'],
        },
      ],
    });

    if (!quiz) {
      return res.status(404).json({
        success: false,
        error: 'Quiz not found',
      });
    }

    if (!Array.isArray(quiz.questions) || quiz.questions.length === 0) {
      return res.status(400).json({
        success: false,
        error: 'Quiz has no questions',
      });
    }

    // Calculate score
    let totalScore = 0;
    let pointsEarned = 0;
    const scoredAnswers = {};

    for (const question of quiz.questions) {
      const userAnswer = answers[question.id];
      const isCorrect = compareAnswers(userAnswer, question.correctAnswer);

      scoredAnswers[question.id] = {
        userAnswer,
        correct: isCorrect,
        points: isCorrect ? question.points : 0,
      };

      pointsEarned += isCorrect ? question.points : 0;
      totalScore += question.points;
    }

    const derivedTotalPoints = quiz.questions.reduce((sum, question) => sum + (question.points || 0), 0);
    const quizTotalPoints = quiz.totalPoints > 0 ? quiz.totalPoints : derivedTotalPoints;

    if (!quizTotalPoints || quizTotalPoints <= 0) {
      return res.status(400).json({
        success: false,
        error: 'Quiz is not configured with valid points',
      });
    }

    const scorePercentage = Math.round((pointsEarned / quizTotalPoints) * 100);
    const passed = scorePercentage >= quiz.passingScore;

    // Store optional assessment emotion report in attempt metadata.
    if (emotionReport && typeof emotionReport === 'object') {
      scoredAnswers.__emotionReport = emotionReport;
    }

    // Create progress record
    const lastAttempt = await QuizProgress.findOne({
      where: { userId, quizId },
      order: [['attempt', 'DESC']],
    });

    const attempt = (lastAttempt?.attempt || 0) + 1;

    const progress = await QuizProgress.create({
      userId,
      quizId,
      attempt,
      score: scorePercentage,
      pointsEarned,
      totalPoints: quizTotalPoints,
      passed,
      timeSpent,
      answers: scoredAnswers,
      completedAt: new Date(),
    });

    // Update quiz stats
    const allAttempts = await QuizProgress.findAll({
      where: { quizId },
    });

    const totalAttempts = allAttempts.length;
    const avgScore = Math.round(
      allAttempts.reduce((sum, a) => sum + a.score, 0) / totalAttempts
    );

    quiz.attemptCount = totalAttempts;
    quiz.averageScore = avgScore;
    quiz.totalPoints = quizTotalPoints;
    await quiz.save();

    await syncLeaderboardForUser(userId);

    res.json({
      success: true,
      data: {
        progress,
        scorePercentage,
        passed,
        pointsEarned,
        totalPoints: quizTotalPoints,
        attempt,
        emotionReport: scoredAnswers.__emotionReport || null,
      },
    });
  } catch (error) {
    console.error('SubmitQuizAttempt error:', error);
    res.status(500).json({
      success: false,
      error: error?.message || 'Failed to submit quiz',
    });
  }
};

